#include<iostream>
using namespace std;
int main(){
    int x = 5 ;
    int y = 2 ;
    cout<<x+y<<endl;
    cout<<x-y<<endl;
    cout<<x*y<<endl;
    cout<<x/y<<endl;
    cout<<x++<<endl;  //increment operations
    cout<<++x<<endl;
    float u = 5 ;
    float v = 2 ;
    cout<<u/v<<endl;
    cout<<5/2<<endl;
    cout<<5.0/2<<endl;
    cout<<5/2.0<<endl;
    cout<<5+3.14<<endl;
}